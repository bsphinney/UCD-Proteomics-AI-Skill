#!/usr/bin/env python3
"""docs/SKILL_INVENTORY.md lists every file the skill ships, is current, and leaves nothing blank.

    python3 -m unittest discover -s tools -v

The inventory is generated by tools/make_inventory.py from each file's own header. These tests
fail when:
  * a shipped file has no entry, or an entry names a file that is gone;
  * the committed page differs from a fresh generation (a header changed, a file was added or
    removed, and nobody ran `python3 tools/make_inventory.py`);
  * an entry says "no description": the file's header does not say what it does (write a one-line
    header in the file itself: a docstring, a first comment block, a first heading and line, or a
    JSON "_about");
  * a file falls into no job group (add a rule to GROUPS in tools/make_inventory.py);
  * the page holds a real identifier (the skill's own identifier rule).
Standard library only, like the skill's tests.
"""
import json
import os
import re
import shutil
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
TOOLS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import make_inventory as mi  # noqa: E402

ENTRY = re.compile(r"^\| `([^`]+)` \|", re.M)


class TheCommittedInventory(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.path = os.path.join(REPO, mi.OUT_REL)
        try:
            with open(cls.path, encoding="utf-8") as fh:
                cls.committed = fh.read()
        except FileNotFoundError:
            cls.committed = None
        cls.fresh, cls.rows = mi.render(REPO)

    def setUp(self):
        self.assertIsNotNone(self.committed, f"no {mi.OUT_REL}: run python3 tools/make_inventory.py")

    def test_every_shipped_file_has_an_entry(self):
        shipped = mi.shipped_files(REPO)
        self.assertGreater(len(shipped), 50, "the walk found almost nothing: is SKILL_REL right?")
        listed = ENTRY.findall(self.committed)
        self.assertEqual(len(listed), len(set(listed)), "a file listed twice")
        outside_tests = {f for f in shipped if not f.startswith("tests/")}
        self.assertEqual(sorted(outside_tests - set(listed)), [], "shipped, not in the inventory")
        self.assertEqual(sorted(set(listed) - outside_tests), [], "in the inventory, not shipped")
        n_tests = sum(f.startswith("tests/") for f in shipped)
        self.assertIn(f"`tests/`: {n_tests} files", self.committed, "the tests summary is stale")

    def test_the_committed_inventory_is_current(self):
        self.assertEqual(self.committed, self.fresh,
                         f"{mi.OUT_REL} is out of date: run python3 tools/make_inventory.py")

    def test_no_entry_says_no_description(self):
        blank = [f"{r['path']}: {r['missing_why']}" for r in self.rows if r["what"] == mi.NO_DESCRIPTION]
        self.assertEqual(blank, [], "these files' headers do not say what they do; write a one-line "
                                    "header in each file (never in the inventory)")

    def test_every_file_has_a_job_group(self):
        other = [r["path"] for r in self.rows if r["group"] == mi.OTHER[0]]
        self.assertEqual(other, [], "add a rule for these to GROUPS in tools/make_inventory.py")

    def test_the_inventory_holds_no_identifier(self):
        hits = mi.identifier_rule(REPO)
        self.assertEqual([n for n, line in enumerate(self.committed.splitlines(), 1) if hits(line)], [])


class TheReader(unittest.TestCase):
    """make_inventory's reading of a header, on small made-up files: a reader that returned ''
    for everything would make every entry 'no description', and one that took the wrong
    paragraph would describe files wrongly without failing anything above."""

    def test_a_docstring_gives_its_first_sentence_without_the_file_name(self):
        src = '"""x_tool.py -- Count the widgets in a run. Then more detail.\n\nAnd more."""\n'
        self.assertEqual(mi.describe("scripts/x_tool.py", src), "Count the widgets in a run.")

    def test_a_comment_block_skips_the_shebang_and_a_note_before_the_named_paragraph(self):
        src = ("#!/usr/bin/env bash\n# =====\n# NO SHEBANG NOTE: sourced, never run.\n#\n"
               "# x.sh -- resolve the thing BY VERSION.\n#\n# Why: details.\nset -e\n")
        self.assertEqual(mi.describe("scripts/x.sh", src), "Resolve the thing BY VERSION.")

    def test_an_indented_list_ends_the_paragraph(self):
        src = "# x.sh -- make two things available:\n#   thing one   for a\n#   thing two   for b\n"
        self.assertEqual(mi.describe("scripts/x.sh", src), "Make two things available:")

    def test_a_hanging_indent_continues_the_sentence(self):
        src = "# x.R  --  tests on the model, for every contrast:\n#   camera and fry side by side. More.\n"
        self.assertEqual(mi.describe("scripts/x.R", src),
                         "Tests on the model, for every contrast: camera and fry side by side.")

    def test_a_question_keeps_its_answer_and_an_abbreviation_does_not_end_a_sentence(self):
        self.assertEqual(mi.first_sentence("Is it on HIVE? If so, print the path. More."),
                         "Is it on HIVE? If so, print the path.")
        self.assertEqual(mi.first_sentence("Compare two runs (e.g. a re-run) of one dataset. More."),
                         "Compare two runs (e.g. a re-run) of one dataset.")
        self.assertEqual(mi.first_sentence("The one table. other.py reads it."), "The one table.")

    def test_a_reference_gives_its_heading_and_first_line(self):
        src = "# Run watcher\n\nA search is long. It runs detached.\n\n## More\n"
        self.assertEqual(mi.describe("references/watcher.md", src),
                         "Run watcher: A search is long.")

    def test_front_matter_gives_the_skill_description(self):
        src = "---\nname: x\ndescription: >\n  Run a search from raw files. Use it when...\n---\n# T\n"
        self.assertEqual(mi.describe("SKILL.md", src), "Run a search from raw files.")

    def test_json_about(self):
        self.assertEqual(mi.describe("scripts/x.json", json.dumps({"_about": "Known bad databases. More here."})),
                         "Known bad databases.")
        self.assertEqual(mi.describe("scripts/y.json", "[1, 2]"), "")

    def test_an_html_page_says_it_in_its_first_comment(self):
        src = "<!doctype html>\n<!-- page.tmpl.html -- The page the tool fills with the data. More. -->\n<html>"
        self.assertEqual(mi.describe("scripts/page.tmpl.html", src),
                         "The page the tool fills with the data.")
        self.assertEqual(mi.describe("scripts/bare.html", "<!doctype html><html></html>"), "")

    def test_a_vendor_file_is_described_by_the_sources_beside_it(self):
        sources = json.dumps({"presets": {"X.workflow": {
            "vendor": "FragPipe 24.0", "vendor_workflow": "X", "source": "workflows/X.workflow",
            "used_for": "DDA with an enzyme rule"}}})
        self.assertEqual(mi.describe("presets/fragpipe/X.workflow", "# Workflow: X\n", sources),
                         "FragPipe 24.0's own X preset (workflows/X.workflow), unchanged, for DDA "
                         "with an enzyme rule.")
        # not listed there: its own header, as for any file
        self.assertEqual(mi.describe("presets/fragpipe/Y.workflow", "# Workflow: Y\n", sources),
                         "Workflow: Y")

    def test_a_label_or_nothing_is_not_a_description(self):
        for desc in ("", "Workflow: DIA_SpecLib_Quant", "RETIRED 2026-08-14.", "x_tool"):
            self.assertFalse(mi.usable(desc, "scripts/x_tool.py")[0], desc)
        self.assertTrue(mi.usable("R mirror of scripts/x.py.", "scripts/x.R")[0])

    def test_a_comment_or_a_docstring_is_not_a_caller(self):
        py = '"""Uses run_search.py, see it."""\n# run_search.py here too\nimport os\n'
        self.assertNotIn("run_search.py", mi.code_text("scripts/a.py", py))
        py2 = 'import fetch_fasta\nsubprocess.run(["python3", "make_report.py"])\n'
        code = mi.code_text("scripts/b.py", py2)
        self.assertIn("import fetch_fasta", code)
        self.assertIn("make_report.py", code)
        sh = '# calls hive_exec.sh in a comment\nbash "$HERE/watch_run.sh" "$1"  # and a comment\n'
        code = mi.code_text("scripts/c.sh", sh)
        self.assertNotIn("hive_exec.sh", code)
        self.assertIn("watch_run.sh", code)

    def test_a_small_tree_end_to_end(self):
        """A made-up skill: every file gets a row, the hook and the callers are found."""
        d = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, d, True)
        sk = os.path.join(d, mi.SKILL_REL)
        for rel, text in {
            ".claude-plugin/plugin.json": json.dumps({"version": "9.9.9", "description": "A test plugin for the tests."}),
            "SKILL.md": "---\ndescription: >\n  Run the made-up pipeline end to end.\n---\n# T\n\n## Step 1. Go\n\n"
                        "Run `python3 scripts/run_search.py --x`.\n",
            "hooks/hooks.json": json.dumps({"description": "mentions helper.py", "hooks": {"SessionEnd": [
                {"hooks": [{"type": "command", "command": "python3 scripts/hook_tool.py"}]}]}}),
            "scripts/run_search.py": '"""run_search.py -- Run the search for the made-up pipeline."""\nimport helper\n',
            "scripts/helper.py": '"""helper.py -- A helper module the search imports."""\n',
            "scripts/hook_tool.py": '"""hook_tool.py -- Save the made-up conversation at the end."""\n',
            "tests/identifier_rules.py": "def problems(rel, line):\n    return []\n",
            "tests/test_x.py": "import unittest\nclass T(unittest.TestCase):\n    def test_a(self): pass\n",
        }.items():
            os.makedirs(os.path.dirname(os.path.join(sk, rel)), exist_ok=True)
            with open(os.path.join(sk, rel), "w") as fh:
                fh.write(text)
        sys.modules.pop("identifier_rules", None)
        try:
            text, rows = mi.render(d)
        finally:
            sys.modules.pop("identifier_rules", None)
        by = {r["path"]: r for r in rows}
        self.assertEqual(sorted(by), [".claude-plugin/plugin.json", "SKILL.md", "hooks/hooks.json",
                                      "scripts/helper.py", "scripts/hook_tool.py", "scripts/run_search.py"])
        self.assertTrue(by["scripts/run_search.py"]["runs"].startswith("run directly"))
        self.assertIn("SKILL.md (Step 1. Go)", by["scripts/run_search.py"]["named_in"])
        self.assertEqual(by["scripts/helper.py"]["runs"], "only used by other scripts: run_search.py")
        self.assertTrue(by["scripts/hook_tool.py"]["runs"].startswith("run by the plugin hook"))
        self.assertIn("`tests/`: 2 files: 1 test files holding 1 test methods", text)
        self.assertIn("version 9.9.9", text)


if __name__ == "__main__":
    unittest.main(verbosity=2)
